// Japanese for screens whose upstream text is written directly in Chinese.
//
// The new-interface settings sections (skills, MCP, plugins, system, ...) were never moved to the
// bilingual shell-copy dictionaries upstream, so they show Chinese even in English mode. This pass
// wraps their visible Chinese literals in zj(zh, ja), which returns the Japanese text only in the
// new interface with Japanese selected and leaves the Chinese (and the classic interface) unchanged.
//
// Strings that also act as data (compared, switched on, used as object keys, literal types, lookup
// keys) are never wrapped, so behaviour does not depend on the display language.
const fs = require('node:fs');
const path = require('node:path');

const HAN = /[一-鿿]/;
const HELPER = 'components/shell/zh-ja.ts';
const HELPER_SOURCE = `/** Japanese for upstream text written directly in Chinese (generated by localization/zh-literals.cjs). */
import { readShellLanguage } from './shell-language';
import { readShellPresentation } from './shell-presentation';
import { ZH_JA_DATA, ZH_JA_DATA_TEMPLATES } from './zh-ja-data';

function japanese(): boolean {
  try {
    return readShellPresentation() === 'v2' && readShellLanguage() === 'ja';
  } catch {
    // A test that mocks the shell preferences without these readers keeps the original Chinese.
    return false;
  }
}

/** The Japanese text in the new interface with Japanese selected; otherwise the original Chinese. */
export function zj(zh: string, ja: string): string {
  return japanese() ? ja : zh;
}

/** Japanese for Chinese that arrives as data (server settings registry, skill categories); otherwise unchanged. */
export function zjd(value: string): string;
export function zjd(value: string | undefined): string | undefined;
export function zjd(value: string | undefined): string | undefined {
  if (value === undefined || !japanese()) return value;
  if (Object.hasOwn(ZH_JA_DATA, value)) return ZH_JA_DATA[value];
  // Values the server already interpolated (a brand name, for example) match their template.
  for (const [pattern, ja] of ZH_JA_DATA_TEMPLATES) {
    const match = pattern.exec(value);
    if (match) return ja.replace(/\\{(\\d+)\\}/g, (_, index: string) => match[Number(index) + 1] ?? '');
  }
  return value;
}

/** zj for templates: the caller evaluates the values once and the chosen template receives them. */
export function zjf<A extends unknown[]>(zh: (...values: A) => string, ja: (...values: A) => string, ...values: A): string {
  return (japanese() ? ja : zh)(...values);
}
`;

// Calls whose string arguments are keys or patterns, not text shown to people.
const KEY_CALLS = new Set([
  't', 'text', 'tt', 'useMemberText', 'includes', 'startsWith', 'endsWith', 'indexOf', 'lastIndexOf', 'has', 'get',
  'set', 'delete', 'split', 'replace', 'replaceAll', 'match', 'matchAll', 'test', 'search', 'require', 'Symbol',
  'getItem', 'setItem', 'removeItem', 'querySelector', 'querySelectorAll', 'getAttribute', 'localeCompare',
  'getElementById', 'RegExp', 'zj',
]);
const KEY_ATTRIBUTES = new Set(['key', 'id', 'className', 'href', 'src', 'value', 'name', 'htmlFor', 'role', 'type',
  'data-testid', 'data-test-id', 'defaultValue']);

const FUNCTION = /Function|ObjectMethod|ClassMethod|ClassPrivateMethod/;

function visit(node, callback, parent, key, inFunction = false) {
  if (!node || typeof node.type !== 'string') return;
  if (callback(node, parent, key, inFunction) === false) return;
  const inner = inFunction || FUNCTION.test(node.type);
  for (const [field, value] of Object.entries(node)) {
    if (field === 'loc' || field === 'leadingComments' || field === 'trailingComments' || field === 'innerComments') continue;
    if (Array.isArray(value)) value.forEach(child => visit(child, callback, node, field, inner));
    else if (value && typeof value.type === 'string') visit(value, callback, node, field, inner);
  }
}

function calleeName(call) {
  const callee = call.callee;
  if (callee.type === 'Identifier') return callee.name;
  if (callee.type === 'MemberExpression' && !callee.computed) return callee.property.name;
  return null;
}

function templateKey(node) {
  if (!node.quasis.every(part => part.value.cooked !== null)) return null;
  return node.quasis.map((part, index) => `${index ? `{${index - 1}}` : ''}${part.value.cooked}`).join('');
}

/** Strings that behave as data anywhere in the given sources. */
function collectDataStrings(parser, files, read, where) {
  const data = new Set();
  let current = '';
  const add = node => {
    const value = node?.type === 'StringLiteral' && HAN.test(node.value) ? node.value :
      node?.type === 'TemplateLiteral' && !node.expressions.length ? node.quasis[0].value.cooked : undefined;
    if (value === undefined) return;
    data.add(value);
    where?.(value, `${current}:${node.loc.start.line}`);
  };
  for (const file of files) {
    current = file;
    const ast = parse(parser, file, read(file));
    // The member editor's text tables are keyed by their Chinese and read only through t('…') lookups.
    const lookupTable = /[\\/]components[\\/]members[\\/]/.test(file);
    visit(ast.program, (node, parent, key) => {
      if (lookupTable && (node.type === 'ObjectProperty' || node.type === 'ObjectMethod')) return;
      if (node.type === 'BinaryExpression' && ['===', '!==', '==', '!='].includes(node.operator)) {
        add(node.left);
        add(node.right);
      } else if (node.type === 'SwitchCase') add(node.test);
      else if ((node.type === 'ObjectProperty' || node.type === 'ObjectMethod' || node.type === 'ClassProperty' ||
        node.type === 'TSPropertySignature') && !node.computed) add(node.key);
      else if (node.type === 'MemberExpression' && node.computed) add(node.property);
      else if (node.type === 'TSLiteralType') add(node.literal);
      else if (node.type === 'TSEnumMember') add(node.initializer);
      else if (node.type === 'CallExpression' && KEY_CALLS.has(calleeName(node)) && !bilingualCall(node)) node.arguments.forEach(add);
      else if (node.type === 'NewExpression' && node.callee.name === 'Map' && node.arguments[0]?.type === 'ArrayExpression') {
        for (const pair of node.arguments[0].elements) if (pair?.type === 'ArrayExpression') add(pair.elements[0]);
      }
    });
  }
  return data;
}

/** t('中文', 'English'): an inline bilingual choice that shows the Chinese whenever the language is not English. */
function bilingualCall(node) {
  const [zh, en] = node.arguments;
  return node.callee.type === 'Identifier' && node.callee.name === 't' && node.arguments.length === 2 &&
    containsHan(zh) && !containsHan(en);
}

/** Whether any string or template text inside the expression is Chinese. */
function containsHan(node) {
  let found = false;
  visit(node, current => {
    if (found) return false;
    if (current.type === 'StringLiteral' && HAN.test(current.value)) found = true;
    if (current.type === 'TemplateElement' && HAN.test(current.value.cooked ?? '')) found = true;
  });
  return found;
}

function parse(parser, file, text) {
  return parser.parse(text, { sourceType: 'module', plugins: ['typescript', ...(file.endsWith('.tsx') ? ['jsx'] : [])] });
}

function quote(value) {
  return JSON.stringify(value);
}

function templateCall(node, text, english, japanese, zh) {
  const slots = [...japanese.matchAll(/\{(\d+)\}/g)].map(match => Number(match[1]));
  if (slots.length !== node.expressions.length || slots.some((slot, index) => slot !== index)) {
    throw new Error(`Keep template placeholders in order for ${JSON.stringify(zh)}`);
  }
  // The values are evaluated once, where they were; each template only receives them.
  const names = node.expressions.map((_, index) => `__zj${index}`);
  const escape = part => JSON.stringify(part).slice(1, -1).replaceAll('`', '\\`').replaceAll('${', '\\${');
  const build = parts => '`' + parts.map((part, index) => index === 0 ? part : '${' + names[index - 1] + '}' + part).join('') + '`';
  const chinese = build(node.quasis.map(part => escape(part.value.cooked)));
  const translated = build(japanese.split(/\{\d+\}/g).map(escape));
  const values = node.expressions.map(expression => text.slice(expression.start, expression.end)).join(', ');
  return `zjf((${names.join(', ')}) => ${chinese}, (${names.join(', ')}) => ${translated}, ${values})`;
}

/**
 * Wraps the visible Chinese literals of `files`. Returns { edits: Map<file, text>, inventory, applied, skipped }.
 * dictionary: Map<chinese, japanese>; keys of templates use {0}, {1} for their expressions.
 */
function localizeChineseLiterals({ parser, src, files, dictionary, englishDictionary, dataScope, read = file => fs.readFileSync(file, 'utf8') }) {
  const data = collectDataStrings(parser, dataScope, read);
  const edits = new Map();
  const inventory = new Map();
  const applied = new Set();
  const skippedData = new Set();
  const lazy = new Set();
  const eager = [];
  for (const file of files) {
    const text = read(file);
    const ast = parse(parser, file, text);
    const changes = [];
    const used = new Set();
    // A module-level property is read again on each access, so the language is decided when it is shown.
    const replace = (node, parent, key, inFunction, call) => {
      used.add(call.slice(0, call.indexOf('(')));
      if (!inFunction && parent?.type === 'ObjectProperty' && key === 'value' && !parent.computed && !parent.shorthand) {
        const name = text.slice(parent.key.start, parent.key.end);
        changes.push([parent.start, parent.end, `get ${name}() {\n    return ${call};\n  }`]);
        lazy.add(file);
      } else {
        if (!inFunction) eager.push(`${path.relative(src, file).replaceAll('\\', '/')}:${node.loc.start.line}`);
        changes.push([node.start, node.end, parent?.type === 'JSXAttribute' ? `{${call}}` : call]);
      }
    };
    const note = (key, line) => {
      if (!inventory.has(key)) inventory.set(key, new Set());
      inventory.get(key).add(`${path.relative(src, file).replaceAll('\\', '/')}:${line}`);
    };
    const callback = (node, parent, key, inFunction) => {
      if (node.type === 'ImportDeclaration' || node.type === 'ExportAllDeclaration' ||
        (node.type === 'ExportNamedDeclaration' && node.source)) return false;
      if (node.type === 'CallExpression' && node.callee.type === 'MemberExpression' &&
        node.callee.object.type === 'Identifier' && node.callee.object.name === 'console') return false;
      if (node.type.startsWith('TS') && node.type !== 'TSAsExpression' && node.type !== 'TSSatisfiesExpression' &&
        node.type !== 'TSNonNullExpression') return false;
      if (node.type === 'TaggedTemplateExpression') return false;
      // Bilingual catalogues get Japanese from their English side (localize.cjs), not from their Chinese.
      if (node.type === 'CallExpression' && calleeName(node) === 'defineShellCopy') return false;
      if (node.type === 'CallExpression' && bilingualCall(node)) {
        // Japanese replaces the Chinese side, which t() shows for every language except English.
        const [zh, en] = node.arguments;
        if (zh.type !== 'StringLiteral') {
          // A template or a choice between texts: its Chinese parts are translated as usual.
          visit(zh, callback, node, 'arguments', inFunction);
          return false;
        }
        note(zh.value, zh.loc.start.line);
        const japanese = dictionary.get(zh.value) ?? englishDictionary?.get(en.value);
        if (japanese !== undefined) {
          changes.push([zh.start, zh.end, `zj(${quote(zh.value)}, ${quote(japanese)})`]);
          used.add('zj');
          applied.add(zh.value);
        }
        return false;
      }
      if (node.type === 'CallExpression' && KEY_CALLS.has(calleeName(node))) return false;
      if (node.type === 'JSXAttribute' && KEY_ATTRIBUTES.has(node.name.name)) return false;
      if (node.type === 'Directive') return false;

      if (node.type === 'JSXText') {
        const trimmed = node.value.trim();
        if (!HAN.test(trimmed)) return;
        const collapsed = trimmed.replace(/\s*\n\s*/g, ' ');
        note(collapsed, node.loc.start.line);
        // JSX text is only ever shown, even when the same words also serve as data elsewhere.
        const japanese = dictionary.get(collapsed);
        if (japanese === undefined) return;
        const lead = node.value.slice(0, node.value.indexOf(trimmed[0]));
        const tail = node.value.slice(node.value.lastIndexOf(trimmed.at(-1)) + 1);
        const keep = value => /\n/.test(value) ? value : value.replace(/ +/g, "{' '}");
        changes.push([node.start, node.end, `${keep(lead)}{zj(${quote(collapsed)}, ${quote(japanese)})}${keep(tail)}`]);
        used.add('zj');
        if (!inFunction) eager.push(`${path.relative(src, file).replaceAll('\\', '/')}:${node.loc.start.line}`);
        applied.add(collapsed);
        return;
      }
      if (node.type === 'StringLiteral') {
        if (!HAN.test(node.value)) return;
        if (parent && (key === 'key' && !parent.computed && /Property|Method/.test(parent.type))) return;
        if (parent?.type === 'MemberExpression' && parent.computed && key === 'property') return;
        note(node.value, node.loc.start.line);
        // A display attribute (title, placeholder, aria-label, ...) is only shown; key attributes were skipped above.
        if (parent?.type !== 'JSXAttribute' && data.has(node.value)) return void skippedData.add(node.value);
        const japanese = dictionary.get(node.value);
        if (japanese === undefined) return;
        replace(node, parent, key, inFunction, `zj(${quote(node.value)}, ${quote(japanese)})`);
        applied.add(node.value);
        return;
      }
      if (node.type === 'TemplateLiteral') {
        const english = templateKey(node);
        if (english === null || !HAN.test(node.quasis.map(part => part.value.cooked).join(''))) return;
        note(english, node.loc.start.line);
        if (data.has(english)) return void skippedData.add(english);
        const japanese = dictionary.get(english);
        if (japanese === undefined) return;
        replace(node, parent, key, inFunction, templateCall(node, text, english, japanese, english));
        applied.add(english);
        return false;
      }
    };
    visit(ast.program, callback);
    if (!changes.length) continue;
    let result = text;
    let end = result.length;
    for (const [start, stop, replacement] of changes.sort((a, b) => b[0] - a[0])) {
      if (stop > end) throw new Error(`${file}: overlapping Chinese-literal edits`);
      result = result.slice(0, start) + replacement + result.slice(stop);
      end = start;
    }
    const helper = path.join(src, HELPER);
    let specifier = path.relative(path.dirname(file), helper).replaceAll('\\', '/').replace(/\.ts$/, '');
    if (!specifier.startsWith('.')) specifier = `./${specifier}`;
    // Names another integration step already imported from the helper are not imported twice.
    const imported = new Set(ast.program.body.filter(node => node.type === 'ImportDeclaration' && node.source.value === specifier)
      .flatMap(node => node.specifiers.map(item => item.local.name)));
    const missing = [...used].filter(name => !imported.has(name)).sort();
    const importLine = missing.length ? `import { ${missing.join(', ')} } from '${specifier}';\n` : '';
    // Directives such as 'use client' must stay first, even after a leading comment; every edit comes later.
    const directive = ast.program.directives.at(-1);
    if (directive) {
      const lineEnd = result.indexOf('\n', directive.end);
      const at = lineEnd < 0 ? result.length : lineEnd + 1;
      result = result.slice(0, at) + importLine + result.slice(at);
    } else result = importLine + result;
    parser.parse(result, { sourceType: 'module', plugins: ['typescript', ...(file.endsWith('.tsx') ? ['jsx'] : [])] });
    edits.set(file, result);
  }
  if (edits.size) edits.set(path.join(src, HELPER), HELPER_SOURCE);
  return { edits, inventory, applied, skippedData, lazyFiles: lazy, eager };
}

module.exports = { localizeChineseLiterals, collectDataStrings, HAN };
